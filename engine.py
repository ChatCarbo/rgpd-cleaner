def t(lang: str, key: str, *args, **kwargs) -> str:
    template = MESSAGES.get(lang, MESSAGES["en"]).get(key, key)
    return template.format(*args, **kwargs)

def log(msg: str):
    print(json.dumps({"type": "log", "msg": msg}, ensure_ascii=False), flush=True)

def emit_account(name, domain, contact, reliability, jdm_url, draft, notes="", method="email", action_url="", instructions="", requires_login=False):
    data = {"type": "account", "name": name, "domain": domain, "contact": contact, "reliability": reliability, "justdeleteme": jdm_url, "draft": draft, "notes": notes, "method": method, "action_url": action_url, "instructions": instructions, "requires_login": requires_login}
    print(json.dumps(data, ensure_ascii=False), flush=True)

def emit_done(out_dir: str, count: int):
    print(json.dumps({"type": "done", "dir": out_dir, "count": count}, ensure_ascii=False), flush=True)

def emit_error(msg: str):
    print(json.dumps({"type": "error", "msg": msg}, ensure_ascii=False), flush=True)

def load_jdm_database(lang: str):
    paths = [Path("sites.json"), Path("jdm-master/_data/sites.json")]
    json_path = next((p for p in paths if p.exists()), None)
    if not json_path: return {}
    try:
        with open(json_path, "r", encoding="utf-8") as f:
            sites_list = json.load(f)
            db = {}
            for site in sites_list:
                name = site.get("name", "").lower()
                notes = site.get("notes", site.get("note", ""))
                notes_localized = site.get("notes_fr") or notes if lang == "fr" else notes
                site_info = {"url": site.get("url", ""), "difficulty": site.get("difficulty", "hard"), "notes": notes_localized, "email": site.get("email", "")}
                db[name] = site_info
                for dom in site.get("domains", []): db[dom.lower()] = site_info
            return db
    except Exception: return {}

# 👇 NOUVELLE FONCTION : Recherche intelligente
def find_best_jdm_match(site_key, jdm_db):
    # 1. Match exact (le plus fréquent)
    if site_key in jdm_db:
        return jdm_db[site_key]
    
    # 2. Match partiel (ex: "spotify" est dans "spotify.com" ou inversement)
    for key, info in jdm_db.items():
        if key in site_key or site_key in key:
            return info
            
    # 3. Aucun match
    return {}

def classify_deletion_method(jdm_info, site_key, lang):
    difficulty = jdm_info.get("difficulty", "N/A")
    url = jdm_info.get("url", "")
    notes = jdm_info.get("notes", "")
    email = jdm_info.get("email", "")
    
    defaults = {
        "fr": {"direct": "Allez dans les paramètres.", "form": "Formulaire RGPD.", "email": "Envoyez un email.", "ticket": "Ouvrez un ticket.", "impossible": "Impossible."},
        "en": {"direct": "Go to settings.", "form": "GDPR form.", "email": "Send email.", "ticket": "Open ticket.", "impossible": "Impossible."}
    }[lang]

    # 👇 Si on a une URL, on propose TOUJOURS une action directe, même si N/A
    if url:
        if difficulty == "medium": return {"method": "form", "action_url": url, "instructions": notes or defaults["form"], "requires_login": False}
        if difficulty == "hard": return {"method": "ticket", "action_url": url, "instructions": notes or defaults["ticket"], "requires_login": True}
        return {"method": "direct", "action_url": url, "instructions": notes or defaults["direct"], "requires_login": True}
        
    # Si pas d'URL, on tente l'email
    if email:
        return {"method": "email", "action_url": f"mailto:{email}", "instructions": notes or defaults["email"], "requires_login": False}
    
    return {"method": "impossible", "action_url": "", "instructions": notes or defaults["impossible"], "requires_login": False}

