def generate_draft(out_dir, domain, site_name, email, name, method, action_url, instructions, contact, lang):
    safe_domain = domain.replace("/", "_").replace(":", "_").replace(" ", "_")
    file_path = out_dir / MESSAGES[lang]["draft_filename"].format(safe_domain)
    header = t(lang, f"hdr_{method}", site_name=site_name, action_url=action_url or t(lang, "no_url"), instructions=instructions or t(lang, "no_instructions"), contact=contact or t(lang, "no_contact"), email=email)
    body = TEMPLATE_RGPD.format(site_name=site_name, domain=domain, email=email, name=name)
    with open(file_path, "w", encoding="utf-8") as f:
        f.write(header + body)
    return file_path

def clean_domain(site_key):
    clean = re.sub(r'^https?://(www\.)?', '', site_key).split('/')[0]
    return clean if '.' in clean else clean + ".com"

def find_holehe():
    found = shutil.which("holehe")
    if found: return found
    if os.name == 'nt':
        local = Path.home() / "AppData" / "Local" / "Python"
        if local.exists():
            for py_dir in local.glob("pythoncore-*"):
                c = py_dir / "Scripts" / "holehe.exe"
                if c.exists(): return str(c)
    return "holehe"

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--email", required=True)
    parser.add_argument("--name", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--lang", default="fr", choices=["fr", "en"])
    args = parser.parse_args()

    lang = args.lang
    email_input = args.email.strip()
    name_input = args.name.strip()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    log(t(lang, "start", email_input))
    jdm_db = load_jdm_database(lang)
    if jdm_db: log(t(lang, "db_loaded", len(jdm_db)))
    else: log(t(lang, "db_missing"))

    holehe_path = find_holehe()
    log(t(lang, "using_holehe", holehe_path))
    log(t(lang, "scanning"))

    files_before = set(os.listdir(out_dir))
    try:
        process = subprocess.Popen([holehe_path, email_input, "-C"], cwd=out_dir, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, encoding='utf-8', errors='ignore')
        for line in process.stdout:
            if line.strip(): log(f"[holehe] {line.strip()}")
        process.wait()
    except Exception as e:
        emit_error(t(lang, "holehe_error", str(e)))
        _cleanup_on_exit()
        time.sleep(0.1)
        sys.exit(1)

    new_files = set(os.listdir(out_dir)) - files_before
    valid_files = [f for f in new_files if f.endswith(".csv")]

    if not valid_files:
        log(t(lang, "no_csv"))
        emit_done(str(out_dir.resolve()), 0)
        time.sleep(0.1)
        return

    for f in valid_files: _cleanup_files.add(out_dir / f)

    count = 0
    seen_sites = set()

    for file in valid_files:
        file_path = out_dir / file
        try:
            with open(file_path, newline='', encoding='utf-8-sig', errors='ignore') as fh:
                for row in csv.DictReader(fh):
                    website = row.get('website', row.get('name', 'Unknown'))
                    status = row.get('exists', 'False')
                    if str(status).lower() not in ['true', 'yes', '1', 'found']: continue
                    
                    site_key = website.lower().strip()
                    if site_key in seen_sites: continue
                    seen_sites.add(site_key)

                    # 👇 Utilisation de la recherche intelligente
                    jdm_info = find_best_jdm_match(site_key, jdm_db)
                    difficulty = jdm_info.get("difficulty", "N/A")

                    contact = row.get('emailrecovery', '').strip()
                    if not contact or contact == 'N/A': contact = jdm_info.get("email", "")

                    jdm_url = f"https://www.google.com/search?q=site%3Ajustdeleteme.xyz+{site_key}"
                    action_url = jdm_info.get("url") or ""
                    
                    cls = classify_deletion_method(jdm_info, site_key, lang)

                    draft_path = generate_draft(out_dir, website, website, email_input, name_input, cls["method"], action_url, cls["instructions"], contact, lang)
                    reliability = (f"Difficulté : {difficulty}" if lang == "fr" else f"Difficulty: {difficulty}")

                    emit_account(website, website, contact, reliability, jdm_url, str(draft_path.resolve()), jdm_info.get("notes", ""), cls["method"], action_url, cls["instructions"], cls["requires_login"])
                    count += 1
        except Exception as e:
            log(t(lang, "csv_parse_error", file, str(e)))
        finally:
            try:
                if file_path.exists(): os.remove(file_path)
                _cleanup_files.discard(file_path)
                log(t(lang, "csv_deleted", file))
            except Exception as e:
                log(t(lang, "csv_delete_fail", file, str(e)))

    log(t(lang, "finished"))
    emit_done(str(out_dir.resolve()), count)
    time.sleep(0.1)

if __name__ == "__main__":
    main()